package com.family.shizi.data.content

enum class G2ResourceErrorCode {
    RESOURCE_FILE_MISSING,
    RESOURCE_FILE_EMPTY,
    RESOURCE_BYTES_MISMATCH,
    RESOURCE_SHA256_MISMATCH,
    RESOURCE_MANIFEST_REFERENCE_MISSING,
    RESOURCE_MANIFEST_ORPHAN,
    RESOURCE_MANIFEST_DUPLICATE,
    RESOURCE_IMAGE_FORMAT_INVALID,
    RESOURCE_IMAGE_DIMENSION_INVALID,
    RESOURCE_AUDIO_FORMAT_INVALID,
    RESOURCE_AUDIO_DURATION_INVALID,
    CONTENT_ASSET_REVIEW_INCOMPLETE,
}

data class G2ResourceValidationError(
    val code: G2ResourceErrorCode,
    val path: String,
    val message: String,
)
